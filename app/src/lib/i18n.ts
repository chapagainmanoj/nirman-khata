export type MessageKey = keyof typeof en

/** One pass over the message: a value that itself contains "{name}" is not filled in again, and a
 *  placeholder used twice is filled both times. A missing value (null, undefined) shows as nothing. */
export function t(key: MessageKey, vars?: Record<string, string | number | null | undefined>): string {
  const text: string = en[key]
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name] ?? '') : whole))
}

/** A label map whose values are keys, read through t() each time, so a module-level map follows the
 *  language instead of keeping the text it had at load. Object.entries still lists every label. */
export function translated<K extends string>(keys: Record<K, MessageKey>): Record<K, string> {
  const out = {} as Record<K, string>
  for (const k of Object.keys(keys) as K[]) Object.defineProperty(out, k, { get: () => t(keys[k]), enumerable: true })
  return out
}
